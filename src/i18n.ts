export type TranslationKey = keyof typeof french;
export function translate(locale: Locale, key: TranslationKey): string {
  return locale === "fr" ? french[key] : key;
}
export function translateStatus(locale: Locale, value: string): string {
  if (locale === "fr" && statusesFrench[value.toUpperCase()]) {
    return statusesFrench[value.toUpperCase()];
  }
  return value.replaceAll("_", " ").toLowerCase().replace(/^./, (s) => s.toUpperCase());
}
export function formatLocalDate(locale: Locale, value: string | null | undefined): string {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : "en-GB", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}
